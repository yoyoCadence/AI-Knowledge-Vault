/**
 * Regenerates `src/modules/search/fold-data.ts`, the Traditional → Simplified character table
 * search folds text with (docs/SEARCH_DESIGN.md §2, "Script folding"). The table comes from
 * opencc-data, the OpenCC dictionaries (Apache License 2.0), as distributed by opencc-js. The
 * package is not a dependency: only its dictionary file is read, once, by hand:
 *
 *   npm pack opencc-js@1.4.2 && mkdir opencc && tar -xzf opencc-js-1.4.2.tgz -C opencc
 *   pnpm exec tsx scripts/build-search-fold.ts \
 *     opencc/package/dist/esm-lib/dict/TSCharacters.js 1.4.2
 *
 * Changing the table changes how text is indexed: bump TOKENIZER_VERSION with it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [dictionaryPath, version] = process.argv.slice(2);
if (!dictionaryPath || !version) {
  console.error("usage: tsx scripts/build-search-fold.ts <TSCharacters.js> <opencc-js version>");
  process.exit(2);
}

const source = readFileSync(dictionaryPath, "utf8");
const body = /^export default "([^"]*)";\s*$/.exec(source.trim());
if (!body) throw new Error('unexpected dictionary format: expected `export default "…";`');

const pairs: string[] = [];
for (const entry of body[1]!.split("|")) {
  const [from, to, ...rest] = entry.split(" ");
  // One code point to one code point only: folding must keep offsets (snippet highlights).
  if (!from || !to || rest.length > 0 || [...from].length !== 1 || [...to].length !== 1) {
    throw new Error(`unexpected entry: ${JSON.stringify(entry)}`);
  }
  if (from !== to) pairs.push(from + to);
}
pairs.sort();

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "src/modules/search/fold-data.ts");
writeFileSync(
  out,
  `// Generated by scripts/build-search-fold.ts from opencc-js@${version}
// dist/esm-lib/dict/TSCharacters.js. That data comes from opencc-data
// (https://github.com/nk2028/opencc-data), the OpenCC dictionaries, under the Apache License
// 2.0 (licenses/Apache-2.0.txt, THIRD_PARTY_NOTICES.md). Modified: reformatted into pairs,
// identity entries dropped. Do not edit by hand.

/** ${pairs.length} pairs, each a Traditional code point followed by its Simplified one. */
export const T2S_PAIRS =
  ${JSON.stringify(pairs.join(""))};
`,
);
console.log(`wrote ${pairs.length} pairs to ${path.relative(root, out)}`);
